// LANGUAGE SWITCHER
// ----------------------------------------

const languageSelect = document.querySelector("#languageSelect");

function setLanguage(language) {
  const dictionary = translations[language];

  if (!dictionary) return;

  // Set document language and text direction
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

  // Update translated text
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.innerHTML = dictionary[key];
    }
  });

  // Update placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;

    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.placeholder = dictionary[key];
    }
  });

  // Synchronize language dropdown
  if (languageSelect) {
    languageSelect.value = language;
  }

  // Update document title
  const titles = {
    en: "Ing. Juraj Žittňanský | Software Engineer",
    de: "Ing. Juraj Žittňanský | Software Engineer",
    ar: "يوراي زيتنانسكي | مهندس برمجيات"
  };

  document.title = titles[language];

  // Save language preference
  try {
    localStorage.setItem("preferredLanguage", language);
  } catch (error) {
    console.warn("Could not save language preference:", error);
  }
}


// Listen for dropdown changes
if (languageSelect) {
  languageSelect.addEventListener("change", (event) => {
    setLanguage(event.target.value);
  });
}


// ----------------------------------------
// CONTACT FORM
// ----------------------------------------

const contactForm = document.querySelector("#contactForm");
const formStatus = document.querySelector("#formStatus");

if (contactForm) {
  contactForm.addEventListener("submit", (event) => {
    event.preventDefault();

    const name = contactForm.querySelector('[name="name"]')?.value.trim();
    const email = contactForm.querySelector('[name="email"]')?.value.trim();
    const message = contactForm.querySelector('[name="message"]')?.value.trim();

    const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

    if (!name || !email || !message || !emailPattern.test(email)) {
      if (formStatus) {
        const language = document.documentElement.lang || "en";
        formStatus.textContent =
          translations[language]?.formError || translations.en.formError;
      }
      return;
    }

    const subject = encodeURIComponent(`Portfolio contact from ${name}`);

    const body = encodeURIComponent(
      `Name: ${name}\nEmail: ${email}\n\n${message}`
    );

    const mailtoUrl =
      `mailto:zittnansky.juraj@gmail.com?subject=${subject}&body=${body}`;

    window.location.href = mailtoUrl;
  });
}


